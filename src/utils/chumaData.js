export function getChumaLevel(count) {
  const level = CHUMA_LEVELS.find(lvl => count >= lvl.min && count <= lvl.max);
  return level || CHUMA_LEVELS[CHUMA_LEVELS.length - 1];
}

export function getRoastComment(count) {
  const level = getChumaLevel(count);
  const index = count % level.roasts.length;
  return level.roasts[index];
}

export function generateBogusMetrics(count, durationSeconds) {
  const aerosolVelocity = Math.min(160, Math.max(35, Math.round(40 + count * 2.3 + Math.random() * 8)));
  const lungResignationRisk = Math.min(99.9, (12 + count * 1.75).toFixed(1));
  const decibelPeak = Math.min(115, Math.max(60, Math.round(65 + Math.sqrt(Math.max(1, count)) * 6)));
  const wastedCalories = (count * 0.85).toFixed(2);
  const unnecessaryComputePower = `${Math.min(99.4, (count * 1.9 + 42)).toFixed(1)} TFLOPs`;

  return {
    aerosolVelocity: `${aerosolVelocity} km/h`,
    lungResignationRisk: `${lungResignationRisk}%`,
    decibelPeak: `${decibelPeak} dB`,
    wastedCalories: `${wastedCalories} kcal`,
    unnecessaryComputePower,
    durationFormatted: `${Math.floor(durationSeconds / 60)}m ${durationSeconds % 60}s`
  };
}
